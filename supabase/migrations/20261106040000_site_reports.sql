-- Weekly Site Report (6 Nov 2026 meeting note #5 + clarification #4)
--
-- Today the "weekly site report" is only an SOP reminder on the Reminders page.
-- This builds the actual report: the UI buckets a project's site_photos by ISO
-- week (Mon-start) and shows each week's photos + descriptions. This table adds
-- an optional per-week staff summary/narrative on top of those photo buckets.
-- Weeks are created ON DEMAND (open question (c) default) — a row exists only
-- once someone writes a summary; weeks with photos but no summary still render.
--
-- ⚠️ RUN THIS IN THE SUPABASE SQL EDITOR (production). Then `bun run gen:types`.

create table if not exists "public"."site_reports" (
  "id"         bigint generated by default as identity primary key,
  "project_id" text not null references "public"."projects"("id") on delete cascade,
  "week_start" date not null,                 -- Monday of the ISO week
  "summary"    text,
  "created_by" text references "public"."staff"("id") on delete set null,
  "created_at" timestamptz not null default now(),
  "updated_at" timestamptz not null default now(),
  unique ("project_id", "week_start")
);

create index if not exists "idx_site_reports_project_week"
  on "public"."site_reports" ("project_id", "week_start");

alter table "public"."site_reports" enable row level security;

drop policy if exists "site_reports_read_all" on "public"."site_reports";
create policy "site_reports_read_all"
  on "public"."site_reports" for select using (true);

drop policy if exists "site_reports_write_ops" on "public"."site_reports";
create policy "site_reports_write_ops"
  on "public"."site_reports" for all
  using (public.is_ops_tier()) with check (public.is_ops_tier());

grant select, insert, update, delete on table "public"."site_reports" to "authenticated";
grant select on table "public"."site_reports" to "anon";

-- Stamp created_by on insert; keep updated_at fresh.
create or replace function public.set_site_report_author()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  if new.created_by is null then new.created_by := public.current_staff_id(); end if;
  return new;
end;
$function$;

drop trigger if exists trg_site_report_author on public.site_reports;
create trigger trg_site_report_author
  before insert on public.site_reports
  for each row execute function public.set_site_report_author();

drop trigger if exists trg_site_reports_updated_at on public.site_reports;
create trigger trg_site_reports_updated_at
  before update on public.site_reports
  for each row execute function public.set_updated_at();
